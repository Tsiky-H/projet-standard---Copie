CREATE TABLE CINE_SALLE (
    ID        VARCHAR2(50)  NOT NULL,
    LIBELLE   VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_CINE_SALLE PRIMARY KEY (ID),
    CONSTRAINT UK_CINE_SALLE_LIBELLE UNIQUE (LIBELLE)
);

CREATE TABLE CINE_CATEGORIE_PLACE (
    ID    VARCHAR2(50)  NOT NULL,
