    CONSTRAINT PK_CINE_CATEGORIE_PLACE PRIMARY KEY (ID),
    CONSTRAINT UK_CINE_CATEGORIE_VAL UNIQUE (VAL),
    CONSTRAINT CK_CINE_CATEGORIE_PRIX CHECK (PRIX >= 0)
